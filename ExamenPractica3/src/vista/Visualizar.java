    public void mostrarInfo(){
        /*Creo un objeto cliente en el que guardo el actual, 
        una vez guardado actualizo los jTextField para que muestren los atributos con los getter de Cliente*/
        
        Coche coche = lista.obtenerCoche();
        jTextField1.setText(coche.getMatricula());
        jTextField2.setText(coche.getFechaMatriculacion()+"");
        jTextField3.setText(coche.getPrecio()+"");
    }
    
    public void borrarCoche(){
        if(!lista.esVacia()){
            lista.borrarCoche();
            if(!lista.esVacia()){
                mostrarInfo();
            }else{
                jTextField1.setText("");
                jTextField2.setText("");
                jTextField3.setText("");
            }
        }
    }
